#assignment operators
x = 10
x += 5  # equivalent to x = x + 5
print("x:", x)

#type conversion
y = 3.14
print("y:", y)

#type casting
z = int(y)  # converting float to int
print("z:", z)

a = 10
a -= 3  # equivalent to a = a - 3
print("a:", a)
a *= 2  # equivalent to a = a * 2
print("a:", a)
a/= 4  # equivalent to a = a / 4



